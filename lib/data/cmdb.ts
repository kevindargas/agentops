export function getCi(id?: string) {
  return id ? ciMap.get(id) : undefined
}

export function getCiRelationships(id: string) {
  return {
    upstream: ciRelationships.filter((r) => r.childId === id),
    downstream: ciRelationships.filter((r) => r.parentId === id),
  }
}

